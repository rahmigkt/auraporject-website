"""ProcTHOR-10K (Apache-2.0, AI2) → AURA furniture-layout training records.

ProcTHOR houses are procedurally generated by rules, not drawn by designers. They are used here for what they are
good at — many rooms with doors, windows and furniture at true size — and every room is checked by AURA's own rules
before it may become a training example. Rooms that fail are kept out of the training file and counted in the report.

Usage: python3 procthor_donustur.py <out_dir> <asset-database.json> <split>=<houses.jsonl.gz> ...
Facing: measured from the data (procthor_incele.py) — an object's front is local +z turned by rotation.y, so in AURA's
plan frame (x = x·1000, y = z·1000, front = (sin θ, −cos θ)) θ = 180 − rotation.y.
"""
import gzip, json, math, sys, collections, statistics, os

out, adb_path, splits = sys.argv[1], sys.argv[2], dict(a.split('=') for a in sys.argv[3:])
BB = {a['assetId']: a['boundingBox'] for v in json.load(open(adb_path)).values() for a in v}
# floor furniture worth learning, with AURA's name for it
KIND = {'Sofa': 'sofa', 'ArmChair': 'armchair', 'Bed': 'bed', 'DiningTable': 'dining', 'CoffeeTable': 'coffee', 'SideTable': 'side',
        'Desk': 'desk', 'TVStand': 'tvunit', 'Dresser': 'dresser', 'ShelvingUnit': 'bookcase', 'Chair': 'chair', 'Ottoman': 'ottoman',
        'Toilet': 'toilet', 'Bathtub': 'bathtub', 'Fridge': 'fridge', 'CounterTop': 'counter', 'FloorLamp': 'floorlamp',
        'WashingMachine': 'washer', 'ClothesDryer': 'dryer', 'Safe': 'safe', 'DogBed': 'dogbed', 'Stool': 'stool', 'GarbageCan': 'bin', 'HousePlant': 'plant'}
ROOM = {'Bedroom': 'bedroom', 'LivingRoom': 'living', 'Kitchen': 'kitchen', 'Bathroom': 'bath'}
TR = {'bedroom': 'yatak odası', 'living': 'oturma odası', 'kitchen': 'mutfak', 'bath': 'banyo'}
NAME = {'sofa': 'kanepe', 'armchair': 'berjer', 'bed': 'yatak', 'dining': 'yemek masası', 'coffee': 'orta sehpa', 'side': 'yan sehpa', 'desk': 'çalışma masası',
        'tvunit': 'TV ünitesi', 'dresser': 'şifonyer', 'bookcase': 'raf', 'chair': 'sandalye', 'ottoman': 'puf', 'toilet': 'klozet', 'bathtub': 'küvet',
        'fridge': 'buzdolabı', 'counter': 'tezgâh', 'floorlamp': 'lambader', 'washer': 'çamaşır makinesi', 'dryer': 'kurutma makinesi', 'safe': 'kasa',
        'dogbed': 'köpek yatağı', 'stool': 'tabure', 'bin': 'çöp kovası', 'plant': 'saksı bitkisi'}
AREA = {'bedroom': (7, 25), 'bath': (3, 12), 'kitchen': (5, 25), 'living': (12, 45)}  # m², plausible European flats
LEARN = {'sofa', 'armchair', 'bed', 'dining', 'coffee', 'side', 'desk', 'tvunit', 'dresser', 'bookcase', 'chair', 'ottoman', 'toilet', 'bathtub', 'fridge', 'counter', 'floorlamp', 'washer', 'dryer'}

mm = lambda v: round(v * 1000)
def inside(p, poly):
    r = False
    for i in range(len(poly)):
        (xi, yi), (xj, yj) = poly[i], poly[i - 1]
        if (yi > p[1]) != (yj > p[1]) and p[0] < (xj - xi) * (p[1] - yi) / (yj - yi) + xi: r = not r
    return r
def dseg(p, a, b):
    dx, dy = b[0] - a[0], b[1] - a[1]; L = dx * dx + dy * dy or 1; t = max(0, min(1, ((p[0] - a[0]) * dx + (p[1] - a[1]) * dy) / L))
    return math.hypot(p[0] - a[0] - t * dx, p[1] - a[1] - t * dy)
def edge_d(p, poly): return min(dseg(p, poly[i], poly[(i + 1) % len(poly)]) for i in range(len(poly)))
def rect(c, th, w, d):
    t = math.radians(th); X, F = (math.cos(t), math.sin(t)), (math.sin(t), -math.cos(t))
    return [(c[0] + X[0] * w / 2 * i + F[0] * d / 2 * j, c[1] + X[1] * w / 2 * i + F[1] * d / 2 * j) for i, j in ((-1, -1), (1, -1), (1, 1), (-1, 1))]
def overlap(P, Q, tol=20):
    for poly in (P, Q):
        for i in range(4):
            a, b = poly[i], poly[(i + 1) % 4]; n = (b[1] - a[1], a[0] - b[0]); L = math.hypot(*n) or 1; n = (n[0] / L, n[1] / L)
            p1 = [p[0] * n[0] + p[1] * n[1] for p in P]; p2 = [p[0] * n[0] + p[1] * n[1] for p in Q]
            if max(p1) <= min(p2) + tol or max(p2) <= min(p1) + tol: return False
    return True
def wall_of(wid):  # "wall|room|x0|z0|x1|z1"
    q = wid.split('|'); return (float(q[2]) * 1000, float(q[3]) * 1000), (float(q[4]) * 1000, float(q[5]) * 1000)

def convert(h, idx, split):
    rooms = {r['id']: r for r in h['rooms']}
    polys = {rid: [(mm(p['x']), mm(p['z'])) for p in r['floorPolygon']] for rid, r in rooms.items()}
    ops = []
    for kind, lst in (('door', h.get('doors', [])), ('window', h.get('windows', []))):
        for o in lst:
            (x0, y0), (x1, y1) = wall_of(o['wall0']); L = math.hypot(x1 - x0, y1 - y0) or 1; ux, uy = (x1 - x0) / L, (y1 - y0) / L
            a, b = o['holePolygon'][0]['x'] * 1000, o['holePolygon'][1]['x'] * 1000
            ops.append({'kind': kind, 'rooms': [o.get('room0'), o.get('room1')], 'p0': [round(x0 + ux * a), round(y0 + uy * a)], 'p1': [round(x0 + ux * b), round(y0 + uy * b)],
                        'width': round(b - a), 'sill': round(o['holePolygon'][0]['y'] * 1000), 'height': round((o['holePolygon'][1]['y'] - o['holePolygon'][0]['y']) * 1000)})
    out = []
    for rid, r in rooms.items():
        rt = ROOM.get(r['roomType']);
        if not rt: continue
        poly, items = polys[rid], []
        for o in h['objects']:
            t = KIND.get(o['id'].split('|')[0]); bb = BB.get(o['assetId'])
            if not t or not bb: continue
            p = (mm(o['position']['x']), mm(o['position']['z']))
            if not inside(p, poly): continue
            th = (180 - o['rotation']['y']) % 360
            items.append({'kind': t, 'size_mm': [mm(bb['x']), mm(bb['z']), mm(bb['y'])], 'pos_mm': list(p), 'rot_deg': round(th)})
        if not items: continue
        rops = [o for o in ops if rid in o['rooms']]
        # ---- AURA checks -------------------------------------------------------------------------------------
        fails = collections.Counter(); feet = [rect(i['pos_mm'], i['rot_deg'], *i['size_mm'][:2]) for i in items]
        for i, f in enumerate(feet):
            if any(not inside(q, poly) and edge_d(q, poly) > 30 for q in f): fails['dışarı taşıyor'] += 1
            for j in range(i):
                if items[i]['kind'] in ('chair', 'stool') and items[j]['kind'] in ('dining', 'desk', 'counter'): continue
                if items[j]['kind'] in ('chair', 'stool') and items[i]['kind'] in ('dining', 'desk', 'counter'): continue
                if overlap(f, feet[j]): fails['çakışma'] += 1
        for o in rops:
            if o['kind'] != 'door': continue
            m = ((o['p0'][0] + o['p1'][0]) / 2, (o['p0'][1] + o['p1'][1]) / 2); ux, uy = o['p1'][0] - o['p0'][0], o['p1'][1] - o['p0'][1]; L = math.hypot(ux, uy) or 1
            n = (-uy / L, ux / L); w = min(o['width'], 1000)
            for s in (1, -1):  # swing / passage zone on the side inside this room
                c = (m[0] + n[0] * s * (w / 2 + 60), m[1] + n[1] * s * (w / 2 + 60))
                if not inside(c, poly): continue
                zone = rect(c, math.degrees(math.atan2(uy, ux)), w, w)
                if any(overlap(zone, f, 40) for f in feet): fails['kapı önü dolu'] += 1
        for o in rops:  # tall pieces and TV screens never stand in front of a window
            if o['kind'] != 'window': continue
            m = ((o['p0'][0] + o['p1'][0]) / 2, (o['p0'][1] + o['p1'][1]) / 2); ux, uy = o['p1'][0] - o['p0'][0], o['p1'][1] - o['p0'][1]; L = math.hypot(ux, uy) or 1
            n = (-uy / L, ux / L)
            for s_ in (1, -1):
                c = (m[0] + n[0] * s_ * 200, m[1] + n[1] * s_ * 200)
                if not inside(c, poly): continue
                zone = rect(c, math.degrees(math.atan2(uy, ux)), o['width'], 380)
                for it, f in zip(items, feet):
                    h_ = 1500 if it['kind'] == 'tvunit' else it['size_mm'][2]
                    if h_ > o['sill'] + 50 and it['kind'] not in ('chair', 'stool', 'plant', 'bin', 'floorlamp') and overlap(zone, f, 40): fails['pencere önü kapalı'] += 1
        # relations AURA insists on (rules from yerlesim.js); ProcTHOR's coffee tables in particular often float far away
        A = abs(sum(poly[i][0] * poly[i - 1][1] - poly[i - 1][0] * poly[i][1] for i in range(len(poly)))) / 2e6
        if not AREA[rt][0] <= A <= AREA[rt][1]: fails['oda alanı gerçek dışı'] += 1
        by = collections.defaultdict(list)
        for i in items: by[i['kind']].append(i)
        for so in by['sofa']:
            for c in by['coffee']:
                g = math.dist(so['pos_mm'], c['pos_mm']) - so['size_mm'][1] / 2 - c['size_mm'][1] / 2
                if not 300 <= g <= 600: fails['sehpa kanepeden uzak/yakın'] += 1
            for tv in by['tvunit']:
                if not 1800 <= math.dist(so['pos_mm'], tv['pos_mm']) <= 3600: fails['TV mesafesi'] += 1
        ok = not fails
        xs, ys = [p[0] for p in poly], [p[1] for p in poly]
        out.append({'source': {'dataset': 'ProcTHOR-10K', 'license': 'Apache-2.0', 'split': split, 'house': idx, 'room': rid,
                               'note': 'procedural generation, not designer layouts'},
                    'room': {'kind': rt, 'boundary_xy_mm': [list(p) for p in poly], 'area_m2': round(abs(sum(poly[i][0] * poly[i - 1][1] - poly[i - 1][0] * poly[i][1] for i in range(len(poly)))) / 2e6, 2),
                             'bbox_mm': [max(xs) - min(xs), max(ys) - min(ys)]},
                    'openings': [{k: o[k] for k in ('kind', 'p0', 'p1', 'width', 'sill', 'height')} | {'to_outside': None in o['rooms'] or o['rooms'][0] == o['rooms'][1]} for o in rops],
                    'items': items, 'aura_check': {'ok': ok, 'fails': dict(fails)}})
    return out

def prompt(rec):
    r = rec['room']; w, d = r['bbox_mm']
    ops = '; '.join(f"{'kapı' if o['kind'] == 'door' else 'pencere'} {o['width']} mm, {o['p0']}–{o['p1']}" for o in rec['openings'])
    its = '; '.join(f"{NAME[i['kind']]} {i['size_mm'][0]}×{i['size_mm'][1]}" for i in rec['items'] if i['kind'] in LEARN)
    return (f"{TR[r['kind']].capitalize()}, {r['area_m2']} m² ({w}×{d} mm). Köşeler (mm, plan): {r['boundary_xy_mm']}. Açıklıklar: {ops or 'yok'}. "
            f"Yerleştirilecekler (en×derinlik mm): {its}. Her biri için merkez (mm) ve ön yönü (derece; 0 = güneye bakar) ver.")

def main():
    os.makedirs(out, exist_ok=True); stat = collections.Counter(); fails = collections.Counter(); metrics = collections.defaultdict(list)
    with open(f'{out}/yerlesim-egitim.jsonl', 'w') as tr, open(f'{out}/yerlesim-tum-odalar.jsonl', 'w') as al:
        for split, path in splits.items():
            for idx, line in enumerate(gzip.open(path, 'rt')):
                for rec in convert(json.loads(line), idx, split):
                    al.write(json.dumps(rec, ensure_ascii=False) + '\n'); stat[(rec['room']['kind'], rec['aura_check']['ok'])] += 1
                    for k, v in rec['aura_check']['fails'].items(): fails[k] += 1
                    learn = [i for i in rec['items'] if i['kind'] in LEARN]
                    if not rec['aura_check']['ok'] or not learn: continue
                    # relations worth comparing with AURA's rules
                    by = collections.defaultdict(list)
                    for i in learn: by[i['kind']].append(i)
                    for s in by['sofa']:
                        for tv in by['tvunit']: metrics['kanepe–TV mesafesi (mm)'].append(math.dist(s['pos_mm'], tv['pos_mm']))
                        for c in by['coffee']: metrics['kanepe önü–sehpa (mm)'].append(max(0, math.dist(s['pos_mm'], c['pos_mm']) - s['size_mm'][1] / 2 - c['size_mm'][1] / 2))
                    for b in by['bed']: metrics['yatak arkası duvara (mm)'].append(edge_d((b['pos_mm'][0] - math.sin(math.radians(b['rot_deg'])) * b['size_mm'][1] / 2, b['pos_mm'][1] + math.cos(math.radians(b['rot_deg'])) * b['size_mm'][1] / 2), rec['room']['boundary_xy_mm']))
                    tr.write(json.dumps({'id': f"procthor-{rec['source']['split']}-{rec['source']['house']}-{rec['source']['room']}", 'source': rec['source'],
                                         'messages': [{'role': 'user', 'content': prompt(rec)},
                                                      {'role': 'assistant', 'content': json.dumps([{'parca': NAME[i['kind']], 'merkez_mm': i['pos_mm'], 'on_derece': i['rot_deg']} for i in learn], ensure_ascii=False)}]},
                                        ensure_ascii=False) + '\n'); stat['egitim'] += 1
    q = lambda v: {'n': len(v), 'p10': round(statistics.quantiles(v, n=10)[0]), 'medyan': round(statistics.median(v)), 'p90': round(statistics.quantiles(v, n=10)[-1])} if len(v) > 10 else {'n': len(v)}
    rep = {'odalar': {f'{k[0]}:{"geçti" if k[1] else "kaldı"}': v for k, v in stat.items() if isinstance(k, tuple)}, 'egitim_ornegi': stat['egitim'],
           'hata_turleri': dict(fails), 'iliskiler': {k: q(v) for k, v in metrics.items()}}
    json.dump(rep, open(f'{out}/rapor.json', 'w'), ensure_ascii=False, indent=1); print(json.dumps(rep, ensure_ascii=False, indent=1))
main()

"""Generate a conservative member screening envelope using upstream EurocodePy.
No downloaded code is copied into the site. No final furniture certification.
Usage: python tools/engineering/build-seating-screen.py --research-root ../arastirma-temel
"""
import argparse,json,math,subprocess,sys
from pathlib import Path
p=argparse.ArgumentParser();p.add_argument('--research-root',type=Path,required=True);a=p.parse_args()
r=a.research_root.resolve();sys.path[:0]=[str(r/'solver-deps'),str(r/'kaynaklar/eurocodepy/src'),str(r/'kaynaklar/pynite-current')]
from eurocodepy.ec5.materials import SolidTimber,ServiceClass,LoadDuration
from eurocodepy.utils import RectangularCrossSection
from eurocodepy.ec5.uls.cross_section import TimberSectionInput,TimberForces,eurocode5_section_check

GRADES=['D24','D30','D40','D70']
AXIAL=1000.;LATERAL=100.+AXIAL*math.sin(math.radians(20))
def section(shape,radius):
 # Upstream grouped EC5 check uses width/height; CircularCrossSection leaves
 # those zero. Use an explicitly conservative inscribed square, not a patched
 # or silently extrapolated circular result.
 side=(2 if shape=='square' else math.sqrt(2))*radius/1000
 return RectangularCrossSection(side,side)
def check(shape,radius,height,grade):
 # Forces already design/scenario forces; do not relabel as EN furniture test loads.
 s=section(shape,radius);t=SolidTimber(grade,edition='2004')
 inp=TimberSectionInput(s,t,ServiceClass.SC1,LoadDuration.MediumDuration,l_0y=2*height,l_0z=2*height,l_0m=2*height)
 f=TimberForces(n_ed=-AXIAL/1000,my_ed=LATERAL*height/1e6,vy_ed=LATERAL/1000)
 return eurocode5_section_check(inp,f)

rows={shape:{g:[] for g in GRADES} for shape in ['square','round']}
for shape in rows:
 for g in GRADES:
  for h in range(5,606,5):
   lo,hi=0.5,100.
   if not check(shape,hi,h,g).passed:raise ValueError('Envelope search upper bound insufficient')
   for _ in range(18):
    mid=(lo+hi)/2
    if check(shape,mid,h,g).passed:hi=mid
    else:lo=mid
   # Round outwards; lookup uses ceiling height bin, never rounds radius upwards.
   radius=math.ceil(hi*1000)/1000
   assert check(shape,radius,h,g).passed
   assert not check(shape,radius-.002,h,g).passed
   rows[shape][g].append(radius)

sha=lambda path:subprocess.check_output(['git','rev-parse','HEAD'],cwd=path,text=True).strip()
out={'schema':'aura.member-screen/1','source':{'repo':'https://github.com/pcachim/eurocodepy','sha':sha(r/'kaynaklar/eurocodepy'),'edition':'EN1995-1-1:2004 implementation; national annex not verified','license':'LGPL-3.0-or-later, upstream not bundled'},
 'scenario':{'id':'leg-design-scenario-1','axial_N':AXIAL,'lateral_N':LATERAL,'service_class':'SC1','duration':'MediumDuration','end_condition':'ideal fixed-free, effective length2H','minimum_section_prism':True,'round_section':'conservative inscribed square; upstream circular grouped check is unsupported','splay_bound_deg':20,'product_certified':False,'loads_are_furniture_standard_test':False,'excluded':['joint capacity','fatigue','impact','whole product stability','supplier grade verification']},
 'height_step_mm':5,'max_height_mm':605,'grades':GRADES,'required_radius_mm':rows}
dest=Path(__file__).resolve().parents[2]/'assets/forma/seating-screen-data.js'
dest.write_text('// Generated by tools/engineering/build-seating-screen.py; do not hand-edit.\nexport const SEATING_SCREEN = '+json.dumps(out,ensure_ascii=False,separators=(',',':'))+';\n',encoding='utf8')
print('PASS',len(GRADES)*2*121,'native-tool envelope rows; boundary bracketing checked; data:',dest)

"""Generate the browser knowledge subset from the user supplied FDE package.

Dependencies: PyYAML. Run from any directory. Original documents stay in knowledge/.
No prompt, code or model mentioned in the package is executed by the browser.
"""
import json
from pathlib import Path
import yaml

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / 'knowledge/furniture_design_engine'

def read(name):
    return json.loads((SOURCE / name).read_text(encoding='utf-8'))

styles = []
for path in sorted((SOURCE / 'styles').glob('*.yaml')):
    profile = yaml.safe_load(path.read_text(encoding='utf-8'))
    styles.append({key: profile[key] for key in [
        'style_id', 'name', 'name_tr', 'description', 'description_tr',
        'core_principles', 'part_directives', 'forbidden_signals', 'scoring_signature'
    ]})
rules = read('rules/manufacturing_constraints.json')
data = {
    'version': '1.0.0',
    'source': 'user-workspace-20261016',
    'types': read('furniture_parts.json')['taxonomy_set']['types'],
    'styles': styles,
    'rules': [r for key in ['structural_rules','ergonomic_rules','manufacturing_rules','design_logic_rules'] for r in rules[key]],
    'materials': rules['materials'],
}
target = ROOT / 'w4/assets/fde-knowledge-data.js'
target.write_text('// Generated by services/design/build-fde-runtime.py; edit original knowledge files.\n'
                  + 'export const KNOWLEDGE=' + json.dumps(data, ensure_ascii=False, separators=(',', ':')) + ';\n', encoding='utf-8')
print(f'{target.name}: {len(data["types"])} types, {len(styles)} styles, {len(data["rules"])} rules')
